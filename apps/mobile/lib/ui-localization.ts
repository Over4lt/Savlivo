export function translateUi(language: AppLanguage, english: string, values: Record<string, string> = {}) {
  const translated = uiTranslations[language]?.[english];
  const template = typeof translated === "string" ? translated : english;
  return template.replace(/\{(\w+)\}/g, (match, key: string) => values[key] ?? match);
}

